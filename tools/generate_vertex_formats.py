"""Generate portable layouts; runtime registration indices are deliberately absent."""
import argparse
import json
from pathlib import Path
import pprint

ROOT=Path(__file__).resolve().parents[1]
def render():
    data=json.loads((ROOT/'config/vertex_formats.json').read_bytes())
    adapter=json.loads((ROOT/'blender_addon_v044/mhwi_equipmentmorph/direct_export_adapter.json').read_bytes())
    if data['schema']!='mhwi-vertex-formats-v1' or data['exporter_sources']!=adapter['sources']:raise ValueError('Pinned exporter provenance differs')
    formats=data['formats'];seen=set();names=set()
    if len(formats)!=14:raise ValueError('Expected fourteen pinned regular layouts')
    for f in formats:
        code=int(f['disk_code'],16)
        if code in seen or f['name'] in names:raise ValueError('Duplicate format')
        seen.add(code);names.add(f['name']);end=0
        for field in f['fields']:
            if field['offset']!=end or field['size']<=0:raise ValueError('Noncontiguous fields')
            end+=field['size']
        if end!=f['stride'] or f['fields'][:3]!=[dict(field='Position',offset=0,size=12),dict(field='NorTan',offset=12,size=8),dict(field='UV1',offset=20,size=4)]:raise ValueError('Invalid common prefix/stride')
        if f['weight_slots'] not in (0,4,8) or not 1<=f['uv_count']<=4:raise ValueError('Invalid capacities')
        if len(f['elements'])>16 or any(not 0<=int(e['packed'],16)<=0xffffffff for e in f['elements']):raise ValueError('Invalid declaration template')
    python='# Generated by tools/generate_vertex_formats.py; edit config/vertex_formats.json.\nFORMATS = '+pprint.pformat({int(f['disk_code'],16):f for f in formats},sort_dicts=False,width=110)+'\n'
    cpp=['// Generated by tools/generate_vertex_formats.py; edit config/vertex_formats.json.','#pragma once','#include <cstdint>','#include <span>','namespace mhm::vertexformats {','struct Element {const char* semantic;uint32_t packed,reserved;};','struct Field {const char* name;uint32_t offset,size;};','struct Format {uint32_t disk,stride,uvCount,weightSlots;bool color;std::span<const Field> fields;std::span<const Element> elements;};']
    for i,f in enumerate(formats):
        cpp.append('inline constexpr Field fields'+str(i)+'[]{'+','.join('{"'+v['field']+'",'+str(v['offset'])+','+str(v['size'])+'}' for v in f['fields'])+'};')
        cpp.append('inline constexpr Element elements'+str(i)+'[]{'+','.join('{"'+e['semantic']+'",'+e['packed']+','+str(e['reserved'])+'}' for e in f['elements'])+'};')
    cpp.append('inline constexpr Format formats[]{')
    for i,f in enumerate(formats):cpp.append('    {'+f['disk_code']+','+str(f['stride'])+','+str(f['uv_count'])+','+str(f['weight_slots'])+','+str(f['color']).lower()+',fields'+str(i)+',elements'+str(i)+'},')
    cpp+=['};','inline const Format* Resolve(uint32_t disk){for(const auto& f:formats)if(f.disk==disk)return &f;return nullptr;}','}']
    return {ROOT/'blender_addon_v044/mhwi_equipmentmorph/backend/vertex_formats.py':python,ROOT/'runtime/EquipmentMorphDiskConfiguration/vertex_formats.hpp':'\n'.join(cpp)+'\n'}
def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,source in render().items():
        if args.check:
            if not path.exists() or path.read_bytes()!=source.encode('utf-8'):raise ValueError('Stale generated file: '+str(path))
        else:path.write_bytes(source.encode('utf-8'))
    print('PASS: fourteen generated vertex formats'+(' consistent' if args.check else ''))
if __name__=='__main__':main()
